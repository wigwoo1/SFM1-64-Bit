import json,re
from pathlib import Path
from pe_image import Image
im=Image(r'F:\SteamLibrary\steamapps\common\SourceFilmmaker\game\bin\tools\ifm.dll')
ranges=[(0x1038cd00,0x1038cd2f)]
groups=[[] for _ in ranges];active=None
for line in Path('work/ifm-disassembly.txt').open():
    m=re.match(r'\s*([0-9A-F]{8}): ((?:[0-9A-F]{2} )+)\s*(.*)',line)
    if not m:
        c=re.fullmatch(r'\s{12}((?:[0-9A-F]{2} ?)+)\s*',line.rstrip())
        if c and active is not None:active['bytes']+=bytes.fromhex(c[1]).hex()
        continue
    va=int(m[1],16);active=None
    if va>=ranges[-1][1]:break
    for i,(start,end) in enumerate(ranges):
        if start<=va<end:
            active=dict(va=hex(va),bytes=bytes.fromhex(m[2]).hex(),instruction=m[3].strip());groups[i].append(active);break
for (start,end),spans in zip(ranges,groups):
    cursor=start
    for s in spans:
        va=int(s['va'],16);raw=bytes.fromhex(s['bytes'])
        assert va==cursor and im.b[im.offset(va):im.offset(va)+len(raw)]==raw
        cursor+=len(raw)
    assert cursor==end
result=dict(complete_code_bytes=47,routines=groups,findings=['Targetwrapperfield14 is attribute pointer; snapshot attributedata4; construct stackfacade vtable10b381bc,attribute,data then call1038cb80(source,count).', 'Inner1038cb80 checks samebase self-assignment and mutation gate, optional undo recording and owner notifications; this is attribute-aware assignment rather than rawvector copy.'],limitations='Inner assignment and notification semantics pending.')
Path('outputs/graph-bookmark-assignment-wrapper-recovery.json').write_text(json.dumps(result,indent=2)+'\n')
print('Verified bookmark assignment facade:',47,'bytes')
